// sandbox-ai web: the page's own texts in English and German. Loaded before app.js.
//
// t("English text with {name}", { name }) gives the text in the page's language with its {placeholders} filled
// in; a text without an entry is shown as it is (in English). What fills a placeholder is put in as text: app.js
// shows every result through textContent, never as markup. "column|Check" is "Check" with a context, for a word
// that needs another German one there; English shows it without the "column|".
// N_("text") only marks a text kept in a table (app.js translates it with t() where it is shown).
//
// The language: what was chosen in the page (kept in this browser), else the browser's (German for de*), else
// English. The German wording is the desktop app's (projects/sandbox-ai-app/sandbox_ai_app/i18n.py): the same
// words for the same things (Freigaben, Start, Sitzung, Arbeitsordner for a start's workspace, Workspace for one
// added while it runs, Verbinden for attach, Vorlage for preset). What the server and the hosts say (names,
// questions, a command's output, an API error) is shown as it comes, and so are commands and options.
// tests/test_web_i18n.py checks that every key of app.js has its German entry with the same placeholders.
"use strict";

const LANGUAGES = [["en", "English"], ["de", "Deutsch"]];
const LANGUAGE_STORE = "sandbox-ai-language";

function N_(text) { return text; }

function browserLanguage() {
  const nav = typeof navigator !== "undefined" ? navigator : null;
  return /^de\b/i.test(String((nav && nav.language) || "")) ? "de" : "en";
}

function chosenLanguage() {
  let stored = null;
  try { stored = localStorage.getItem(LANGUAGE_STORE); } catch (e) { stored = null; }
  return LANGUAGES.some(([code]) => code === stored) ? stored : null;
}

let LANGUAGE = chosenLanguage() || browserLanguage();

// CODE ("en" or "de") from now on, remembered in this browser; anything else: the browser's language again.
function setLanguage(code) {
  const known = LANGUAGES.some(([key]) => key === code);
  LANGUAGE = known ? code : browserLanguage();
  try { if (known) localStorage.setItem(LANGUAGE_STORE, code); else localStorage.removeItem(LANGUAGE_STORE); } catch (e) { /* this page only */ }
  translateDocument();
  return LANGUAGE;
}

function t(key, values) {
  const entry = Object.prototype.hasOwnProperty.call(TEXTS, key) ? TEXTS[key] : null;
  const text = (entry && entry[LANGUAGE]) || String(key).replace(/^[a-z]+\|/, "");
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) =>
    (Object.prototype.hasOwnProperty.call(values, name) ? String(values[name] ?? "") : whole));
}

// The document's language (screen readers, hyphenation) and its fixed texts: an element of index.html with
// data-i18n="KEY" shows t(KEY).
function translateDocument() {
  if (typeof document === "undefined" || !document.documentElement) return;
  document.documentElement.lang = LANGUAGE;
  if (typeof document.querySelectorAll !== "function") return;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.getAttribute("data-i18n"));
}

