"""The first view of every Help section, in English and German: one sentence of what it is for, the page whose
screenshot shows it with the controls numbered on it, and "How do I…" - the most common tasks in short steps, one
line each. The details stay in help_content.py (folded away below); help_view.py shows both. No Qt.

shot is a page key of the window (ui.PAGES); callouts are attributes of that page as the tours name them
(tours.control): the legend under the screenshot uses the tours' names, "Show me" outlines the same control a tour
outlines. A step that starts with "$ " is a command, shown as a block to copy.
"""
from __future__ import annotations

from dataclasses import dataclass

from .tours import Text


@dataclass(frozen=True)
class Task:
    title: Text
    steps: tuple  # Text, one line each


@dataclass(frozen=True)
class View:
    summary: Text
    shot: str
    callouts: tuple
    tasks: tuple


def task(title, *steps):
    return Task(Text(*title), tuple(Text(*s) if isinstance(s, tuple) else Text(s, s) for s in steps))


def view(summary, shot, callouts, *tasks):
    return View(Text(*summary), shot, tuple(callouts), tuple(tasks))


def cmd(line):
    """A step that is a command (the same in both languages)."""
    return ("$ " + line, "$ " + line)


